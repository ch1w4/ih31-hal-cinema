    SELECT screen_id INTO L1 FROM screens WHERE name = '大スクリーン1';
    SELECT screen_id INTO L2 FROM screens WHERE name = '大スクリーン2';
    SELECT screen_id INTO L3 FROM screens WHERE name = '大スクリーン3';
